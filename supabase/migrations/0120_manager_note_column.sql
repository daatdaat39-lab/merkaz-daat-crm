-- מפריד "הערת מנהל" (טקסט חופשי, ניתן-לדריסה) מ-note (יומן-שיחות
-- append-only של הטלפנים) - שתי דריסות-מלאות שהיו קיימות עד כה על note
-- (ייבוא CSV, משיכת-גיליון) דרסו בעבר בטעות יומן-שיחות שלם - זו בדיוק
-- תקרית אובדן-הנתונים שתוקנה הבוקר (0117/0118). מכאן והלאה note נשאר
-- בלעדית יומן-השיחות (append-only, כמו היום), manager_note הוא השדה
-- שהמנהל עורך/מייבא/מושך מגיליון.
-- בכוונה בלי backfill: manager_note מתחיל ריק לכל השורות - אין דרך
-- אמינה להפריד רטרואקטיבית תוכן-מנהל-ישן שכבר מעורבב בתוך note הקיים
-- בלי לנחש/לפגוע בהיסטוריה האמיתית.
alter table public.campaign_contacts
  add column if not exists manager_note text;
